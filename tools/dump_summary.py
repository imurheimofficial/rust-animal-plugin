"""Summarise the BeastmasterDump JSON files into docs/_data/dump-summary.md (English, for the docs).

Usage:  python -I tools/dump_summary.py <dump-folder> <output.md>
"""
import json
import os
import re
import sys

CLIP_RE = re.compile(r"^(AnimationClip|RootMotionData):(.+?)(?: len=([0-9.]+))?$")


def load(folder, name):
    with open(os.path.join(folder, name + ".json"), "r", encoding="utf-8") as f:
        return json.load(f)


def walk(value, path, out):
    """Collect every AnimationClip / RootMotionData reference with the path that leads to it."""
    if isinstance(value, str):
        m = CLIP_RE.match(value)
        if m:
            out.append((path, m.group(1), m.group(2), m.group(3)))
    elif isinstance(value, dict):
        for k, v in value.items():
            walk(v, path + "." + k if path else k, out)
    elif isinstance(value, list):
        for i, v in enumerate(value):
            walk(v, "%s[%d]" % (path, i), out)


def gait_row(agent):
    keys = ["sneakSpeed", "walkSpeed", "jogSpeed", "runSpeed", "sprintSpeed", "fullSprintSpeed"]
    vals = []
    for k in keys:
        v = agent.get(k)
        vals.append("%.2f" % v if isinstance(v, (int, float)) else "-")
    return vals


def main(folder, out_path):
    animals = load(folder, "animals")
    mountables = load(folder, "mountables")
    gestures = load(folder, "gestures")
    items = load(folder, "items")
    horse = load(folder, "horse")
    prefabs = load(folder, "prefabs")
    build = load(folder, "build")
    livestock = load(folder, "convars_livestock")

    L = []
    w = L.append
    w("# Dump summary - Rust build %s (network %s), Oxide %s" % (build.get("protocol"), build.get("network"), build.get("oxide")))
    w("")
    w("Generated by `tools/dump_summary.py` from the dev-server dump (`tools/devplugins/BeastmasterDump.cs`). Raw JSON next to this file.")
    w("")

    # ---------------------------------------------------------------- animals
    living = [a for a in animals if "BaseCorpse" not in a.get("baseChain", [])]
    corpses = [a for a in animals if "BaseCorpse" in a.get("baseChain", [])]
    w("## 1. Animal and creature prefabs (%d living, %d corpses)" % (len(living), len(corpses)))
    w("")
    w("| Prefab | Class | Health | FSM | Sneak | Walk | Jog | Run | Sprint | FullSprint | Swims |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for a in sorted(living, key=lambda r: r["path"]):
        parts = a.get("parts") or {}
        agent = parts.get("RustNavMeshAgent") or {}
        fsm = next((k for k in parts if "FSM" in k or "Fsm" in k), "-")
        g = gait_row(agent) if agent else ["-"] * 6
        swims = agent.get("canSwim", "-") if agent else "-"
        w("| `%s` | %s | %s | %s | %s | %s |" % (a["path"], a["class"].split(".")[-1], a.get("startHealth", "-"), fsm, " | ".join(g), swims))
    w("")
    w("Corpses: " + ", ".join("`%s`" % c["path"] for c in sorted(corpses, key=lambda r: r["path"])))
    w("")

    w("## 2. Animation clips per creature (what the plugin can play)")
    w("")
    for a in sorted(living, key=lambda r: r["path"]):
        clips = []
        walk(a.get("parts") or {}, "", clips)
        if not clips:
            continue
        seen = {}
        for path, kind, name, length in clips:
            key = (kind, name)
            if key not in seen:
                seen[key] = (path, length)
        w("### `%s`" % a["path"])
        for (kind, name), (path, length) in sorted(seen.items(), key=lambda kv: kv[1][0]):
            state = path.split(".")[1] if path.count(".") >= 1 else path
            w("- %s `%s`%s - from `%s`" % ("RM" if kind == "RootMotionData" else "clip", name, " (%ss)" % length if length else "", path))
        w("")

    # ---------------------------------------------------------------- mountables
    w("## 3. Mountable seats")
    w("")
    by_mode = {}
    for m in mountables:
        by_mode.setdefault(m["cameraMode"], 0)
        by_mode[m["cameraMode"]] += 1
    w("Camera modes: " + ", ".join("%s = %d" % kv for kv in sorted(by_mode.items())))
    w("")
    w("### Seats whose camera is not first person")
    w("")
    w("| Prefab | Class | Root? | Pose | Camera | Can wield |")
    w("|---|---|---|---|---|---|")
    for m in sorted(mountables, key=lambda r: r["prefab"]):
        if m["cameraMode"] != "FirstPerson":
            w("| `%s` | %s | %s | %s | %s | %s |" % (m["prefab"], m["class"], m["isRoot"], m["mountPose"], m["cameraMode"], m["canWieldItems"]))
    w("")
    w("### Horseback-pose seats and stand-alone chairs (candidates for animal saddles / hidden seats)")
    w("")
    w("| Prefab | Class | Root? | Pose | Camera | Can wield |")
    w("|---|---|---|---|---|---|")
    for m in sorted(mountables, key=lambda r: r["prefab"]):
        p = m["prefab"]
        if m["mountPose"] == "Horseback" or (m["isRoot"] and ("chair" in p or "seat" in p or "invisible" in p)):
            w("| `%s` | %s | %s | %s | %s | %s |" % (p, m["class"], m["isRoot"], m["mountPose"], m["cameraMode"], m["canWieldItems"]))
    w("")

    # ---------------------------------------------------------------- gestures
    w("## 4. Gestures (%d)" % len(gestures))
    w("")
    w("| Convar | Name | Type | View | Movement | Layer | Anim | Free for all | DLC | Steam item | Hidden |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for g in sorted(gestures, key=lambda r: (r["type"], r["convar"] or "")):
        w("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (g["convar"], g["name"], g["type"], g["viewMode"], g["movement"], g["layer"],
                                                                       g["animation"], g["forceUnlock"], g["dlc"], g["steamItem"], g["hideInWheel"]))
    w("")

    # ---------------------------------------------------------------- items
    w("## 5. Relevant items")
    w("")
    w("| Shortname | Name | Category | Effects / equipment | Held entity |")
    w("|---|---|---|---|---|")
    keywords = ("horse", "saddle", "shoe", "dart", "blowpipe", "trap", "syringe", "spray", "torch", "bone", "rope", "lead",
                "milk", "wool", "beef", "mutton", "meat", "fish", "corn", "potato", "pumpkin", "berry", "apple", "grub", "worm", "seed", "hay", "dung", "water")
    for it in sorted(items["relevant"], key=lambda r: r["shortname"]):
        sn = it["shortname"]
        if not any(k in sn for k in keywords):
            continue
        extra = ""
        if it.get("effects"):
            extra = ", ".join(it["effects"])
        if it.get("equipment"):
            eq = it["equipment"]
            extra = "slot=%s speed=%s" % (eq.get("slot"), eq.get("speedModifier"))
        w("| `%s` | %s | %s | %s | %s |" % (sn, it.get("name"), it.get("category"), extra, it.get("heldEntity") or ""))
    w("")

    # ---------------------------------------------------------------- horse
    w("## 6. Horse")
    w("")
    for h in horse:
        w("### `%s`" % h["path"])
        for mp in h["mountPoints"]:
            w("- mount point: driver=%s bone=`%s` prefab=`%s` pos=%s" % (mp["isDriver"], mp["bone"], mp["prefab"], mp["pos"]))
        f = h["fields"]
        for key in ("gaits", "breeds"):
            if key in f:
                w("- %s:" % key)
                for row in f[key] if isinstance(f[key], list) else []:
                    w("  - %s" % json.dumps(row, ensure_ascii=False))
        for key in ("roadSpeedBonus", "reverseSpeedFactor", "maxAirTimeBeforeRagdoll", "minMaxSlopeAngle", "groundAngleToRecoverFromSlide", "gaitProgressionInterval"):
            if key in f:
                w("- %s = %s" % (key, f[key]))
        w("")

    # ---------------------------------------------------------------- convars
    w("## 7. Livestock settings (ConVar.Livestock)")
    w("")
    for k in sorted(livestock):
        w("- `%s` = %s" % (k, livestock[k]))
    w("")
    w("## 8. Relevant non-entity prefabs (effects, sounds, models) - first 400")
    w("")
    for p in prefabs.get("relevantNonEntityPrefabs", [])[:400]:
        w("- `%s`" % p)
    w("")

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))
    print("written", out_path, len(L), "lines")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
